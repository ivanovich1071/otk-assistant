"""Перекодировка чертёжных шрифтов в юникод по правилам `glossary.md`.

В векторных PDF из КОМПАС знаки Ø и ° приходят отдельным шрифтом `Symbol_A`
обычными латинскими буквами: `Ç` — это Ø, а не «Ç». Поэтому таблица привязана
к имени шрифта: тот же символ в основном шрифте значит совсем другое.
"""
from __future__ import annotations

import re

# Служебный шрифт КОМПАС для знаков, которых нет в GOSTTypeA.
SYMBOL_A = {
    "Ç": "Ø",
    "Å": "°",
    "ã": "↷",   # «повёрнуто», ГОСТ 2.305
    "æ": "○",   # шов по замкнутой линии, ГОСТ 2.312
}

FONT_MAPS: dict[str, dict[str, str]] = {"Symbol_A": SYMBOL_A}

# Замены внутри основного шрифта — из таблицы символов glossary.md.
PLAIN = {
    "•": "×",
    "−": "-",   # математический минус
    "–": "-",   # короткое тире
    " ": " ",
}

# Знак умножения на чертеже набирают латинской или кириллической «х»:
# «М8-6gx20», «32x18x140», «3x45°».
_MUL = re.compile(r"(?<=[0-9A-Za-zА-Яа-я])[xх](?=[0-9])")

# В спецификациях кернинг съедает пробел: «ГОСТ5721-75».
_GOST = re.compile(r"ГОСТ(?=[0-9])")


def decode_span(text: str, font: str) -> str:
    """Символы одного span'а — с учётом шрифта, которым он набран."""
    table = FONT_MAPS.get(font)
    if table:
        text = "".join(table.get(ch, ch) for ch in text)
    return "".join(PLAIN.get(ch, ch) for ch in text)


# В спецификациях кернинг съедает пробел перед номером: «Подшипник3520».
# Четыре буквы до числа не дают разорвать типоразмеры вроде «Ц130L210».
_GLUED_NUMBER = re.compile(r"(?<=[А-Яа-я]{4})(?=\d{3})")


def spec_text(text: str) -> str:
    """Дополнительная чистка для строк спецификации."""
    return _GLUED_NUMBER.sub(" ", normalize(text))


def normalize(text: str) -> str:
    """Замены, которые видны только на собранной строке, а не в отдельном span'е."""
    text = _MUL.sub("×", text)
    text = _GOST.sub("ГОСТ ", text)
    return re.sub(r"[ \t]+", " ", text).strip()
